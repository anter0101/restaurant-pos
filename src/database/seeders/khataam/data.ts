/**
 * Khataam menu seed data (Arabic source: https://www.khataam.com — scraped once and
 * frozen here so the live site is no longer required to seed the database).
 *
 * Identity:
 *   - Branches  : matched by stable `name` (e.g. "Khataam · shebin-a").
 *   - Categories: matched by `nameAr` (single global category per Arabic name).
 *   - MenuItems : matched by (`category`, `nameAr`); `defaultPrice` is the price first
 *                 encountered for the item; per-location overrides live in `branchPrices`
 *                 and are written into `rel_menu_branches`.
 */

export interface KhataamSeedBranch {
  /** Unique stable `branches.name` value. */
  name: string;
  type: BranchType;
  address: string;
  phone?: string;
}

export interface KhataamSeedCategory {
  nameAr: string;
  nameEn: string;
}

export interface KhataamSeedItemBranchPrice {
  /** Must match a `name` of one of the entries in `khataamBranches`. */
  branchName: string;
  price: number;
}

export interface KhataamSeedMenuItem {
  /** Must match a `nameAr` of one of the entries in `khataamCategories`. */
  categoryNameAr: string;
  nameAr: string;
  nameEn: string;
  defaultPrice: number;
  branchPrices: KhataamSeedItemBranchPrice[];
}

