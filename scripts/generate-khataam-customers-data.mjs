#!/usr/bin/env node
/**
 * Parse Khataam customer TSV export into frozen customers.data.ts for seeding.
 *
 * Usage:
 *   node scripts/generate-khataam-customers-data.mjs "path/to/عملاء ختعم 13.7.2026.txt"
 *   KHATAAM_CUSTOMERS_FILE=... node scripts/generate-khataam-customers-data.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT = join(
  __dirname,
  '..',
  'src',
  'database',
  'seeders',
  'khataam',
  'customers.data.ts',
);

const COL_NAME = 1;
const COL_PHONE = 2;
const COL_ADDRESS = 3;
const COL_CUSTOMER_TYPE = 6;
const COL_ALT_PHONE = 12;

const PHONE_RE = /^[\d+\-\s()]{6,20}$/;

function mapSheetCustomerType(raw) {
  const code = String(raw ?? '').trim().toLowerCase();
  if (code === 'c') return 'NORMAL';
  if (code === 's') return 'SPECIAL';
  throw new Error(`Unknown customer type code: ${raw}`);
}

function escapeTsString(value) {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '')
    .replace(/\n/g, '\\n');
}

function isPhoneShaped(value) {
  const trimmed = String(value ?? '').trim();
  return trimmed.length > 0 && PHONE_RE.test(trimmed);
}

function parseLine(line) {
  const cols = line.split('\t');
  const phone = String(cols[COL_PHONE] ?? '').trim();
  if (!phone) {
    return { skipped: true, reason: 'empty-phone' };
  }

  let customerType;
  try {
    customerType = mapSheetCustomerType(cols[COL_CUSTOMER_TYPE]);
  } catch {
    return { skipped: true, reason: 'unknown-type' };
  }

  const name = String(cols[COL_NAME] ?? '').trim();
  if (!name) {
    return { skipped: true, reason: 'empty-name' };
  }

  const address = String(cols[COL_ADDRESS] ?? '').trim();
  const altRaw = String(cols[COL_ALT_PHONE] ?? '').trim();

  const customer = {
    name,
    phone,
    customerType,
  };
  if (address) customer.address = address;
  if (isPhoneShaped(altRaw)) customer.alternativePhone = altRaw;

  return { customer };
}

function main() {
  const inputPath = resolve(
    process.argv[2] ?? process.env.KHATAAM_CUSTOMERS_FILE ?? '',
  );
  if (!inputPath) {
    console.error(
      'Usage: node scripts/generate-khataam-customers-data.mjs <path-to-tsv>',
    );
    process.exit(1);
  }

  const raw = readFileSync(inputPath, 'utf8');
  const lines = raw.split(/\r?\n/).filter((l) => l.trim().length > 0);

  const customers = [];
  const skipped = {
    'empty-phone': 0,
    'unknown-type': 0,
    'empty-name': 0,
    'duplicate-phone': 0,
  };
  const seenPhones = new Set();

  for (const line of lines) {
    const result = parseLine(line);
    if (result.skipped) {
      skipped[result.reason] = (skipped[result.reason] ?? 0) + 1;
      continue;
    }
    const phone = result.customer.phone.trim();
    if (seenPhones.has(phone)) {
      skipped['duplicate-phone']++;
      continue;
    }
    seenPhones.add(phone);
    customers.push(result.customer);
  }

  const normal = customers.filter((c) => c.customerType === 'NORMAL').length;
  const special = customers.filter((c) => c.customerType === 'SPECIAL').length;

  const body = customers
    .map((c) => {
      const parts = [
        `name: '${escapeTsString(c.name)}'`,
        `phone: '${escapeTsString(c.phone)}'`,
        `customerType: CustomerType.${c.customerType}`,
      ];
      if (c.address) parts.push(`address: '${escapeTsString(c.address)}'`);
      if (c.alternativePhone) {
        parts.push(`alternativePhone: '${escapeTsString(c.alternativePhone)}'`);
      }
      return `  { ${parts.join(', ')} }`;
    })
    .join(',\n');

  const output = `import { CustomerType } from 'src/core/enums/customer-type';

export interface KhataamSeedCustomer {
  name: string;
  phone: string;
  alternativePhone?: string;
  address?: string;
  customerType: CustomerType;
}

/** Generated by scripts/generate-khataam-customers-data.mjs — do not edit by hand. */
export const khataamCustomers: KhataamSeedCustomer[] = [
${body},
];
`;

  writeFileSync(OUTPUT, output, 'utf8');

  console.log(`Wrote ${customers.length} customers to ${OUTPUT}`);
  console.log(`  NORMAL=${normal}, SPECIAL=${special}`);
  console.log(
    `  skipped: empty-phone=${skipped['empty-phone']}, unknown-type=${skipped['unknown-type']}, empty-name=${skipped['empty-name']}, duplicate-phone=${skipped['duplicate-phone']}`,
  );
}

main();
